// Calcul des stats du dashboard
export function getDashboardStats(): DashboardStats {
  const biensOccupes = biens.filter(b => b.statut === 'OCCUPE').length;
  const biensDisponibles = biens.filter(b => b.statut === 'DISPONIBLE').length;
  const revenusMois = paiements.filter(p => p.statut === 'PAYE' || p.statut === 'PARTIEL').reduce((sum, p) => sum + p.montant_paye, 0);
  const depensesMois = depenses.filter(d => {
    const date = new Date(d.date_depense);
    return date.getMonth() === currentMonth && date.getFullYear() === currentYear;
  }).reduce((sum, d) => sum + d.montant, 0);
  const paiementsEnRetard = paiements.filter(p => p.statut === 'EN_RETARD').length;
  const travauxEnCours = travaux.filter(t => t.statut === 'EN_COURS').length;

  return {
    total_biens: biens.length,
    biens_occupes: biensOccupes,
    biens_disponibles: biensDisponibles,
    total_locataires: locataires.filter(l => l.actif).length,
    revenus_mois: revenusMois,
    depenses_mois: depensesMois,
    paiements_en_retard: paiementsEnRetard,
    taux_occupation: Math.round((biensOccupes / biens.length) * 100),
    travaux_en_cours: travauxEnCours,
  };
}

